import argparse
import os
import sys
import numpy as np
import matplotlib.pyplot as plt
from PIL import Image

def parse_args():
    parser = argparse.ArgumentParser(description="MNIST Inference Engine using C++ Trained Weights")
    parser.add_argument(
        "--model",
        type=str,
        default="mnist_model.bin",
        help="Path to binary model file generated by C++ (default: mnist_model.bin)"
    )
    parser.add_argument(
        "--image",
        type=str,
        required=True,
        help="Path to input image (e.g., demo/samples/sample_0_label_7.png)"
    )
    parser.add_argument(
        "--no-gui",
        action="store_true",
        help="Do not display matplotlib GUI window (useful for headless environments)"
    )
    return parser.parse_args()

def main():
    args = parse_args()

    # Fallback search path for model if run from demo folder
    if not os.path.exists(args.model):
        candidate = os.path.join("..", args.model)
        if os.path.exists(candidate):
            args.model = candidate

    if not os.path.exists(args.model):
        print(f"[!] Error: Model file not found -> {args.model}")
        print("[!] Hint: Run the C++ engine first to train and generate 'mnist_model.bin'")
        sys.exit(1)

    # Fallback search path for image
    if not os.path.exists(args.image):
        base_dir = os.path.dirname(os.path.abspath(__file__))
        candidate = os.path.join(base_dir, args.image)
        if os.path.exists(candidate):
            args.image = candidate

    if not os.path.exists(args.image):
        print(f"[!] Error: Image file not found -> {args.image}")
        sys.exit(1)

    # Load model weights from binary file
    raw = np.fromfile(args.model, dtype=np.float32)

    # Architecture: 784 -> 128 -> 10
    # Parameters: (128 * 784) + 128 + (10 * 128) + 10 = 101,770 float32 values
    expected_size = (128 * 784) + 128 + (10 * 128) + 10
    if raw.size != expected_size:
        print(f"[!] Error: Model size mismatch! Expected: {expected_size}, Found: {raw.size}")
        sys.exit(1)

    # Weight matrices and bias vectors
    W1 = raw[0 : 128 * 784].reshape(128, 784)
    B1 = raw[128 * 784 : 128 * 784 + 128].reshape(128, 1)

    offset = 128 * 784 + 128
    W2 = raw[offset : offset + 10 * 128].reshape(10, 128)
    B2 = raw[offset + 10 * 128 : offset + 10 * 128 + 10].reshape(10, 1)

    # Load and resize image to 28x28 grayscale
    img = Image.open(args.image).convert('L').resize((28, 28))
    img_data = np.array(img, dtype=np.float32)

    # Normalize pixels to [-1.0, 1.0], matching the C++ preprocessing
    x = ((img_data / 127.5) - 1.0).reshape(784, 1)

    # Forward pass
    z1 = np.dot(W1, x) + B1
    a1 = np.tanh(z1)

    z2 = np.dot(W2, a1) + B2
    exp_z = np.exp(z2 - np.max(z2))
    probs = (exp_z / np.sum(exp_z)).flatten()

    prediction = int(np.argmax(probs))
    confidence = probs[prediction] * 100.0

    print(f"[*] Image      : {args.image}")
    print(f"[*] Model      : {args.model}")
    print(f"[+] Prediction : {prediction} (Confidence: {confidence:.2f}%)")

    if not args.no_gui:
        plt.figure(figsize=(4, 4))
        plt.imshow(img_data, cmap='gray')
        plt.title(f"Prediction: {prediction} ({confidence:.1f}%)", fontsize=14, color='red', fontweight='bold')
        plt.axis('off')
        plt.show()

if __name__ == "__main__":
    main()
